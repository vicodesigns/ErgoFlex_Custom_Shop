import assert from 'node:assert/strict';
import {studioPeopleChanges,peopleEditsFromStudio} from '../experience/studio-people-sync.mjs';
import {adoptRows} from '../experience/studio-sync.mjs';
const leo={key:'people-leo-sit-raise',id:'people-leo-sit-raise',at:[-235,1011],turn:-180,y:60,colors:{top:'#112233'}};
const mia={key:'people-mia-sit-type',id:'people-mia-sit-type',desk:'sit',station:'window-research'};
const key=p=>`scene:highschool:house:person:${p.key}:${p.id}`;
const transform=(x,z,turn=35,scale=1.2)=>({p:{x,y:80,z},q:{x:0,y:Math.sin(turn*Math.PI/360),z:0,w:Math.cos(turn*Math.PI/360)},s:{x:scale*1000,y:scale*1000,z:scale*1000}});
const raw=JSON.stringify({'highschool:house':{transforms:{[key(leo)]:transform(415,1211),[key(mia)]:transform(1200,900)}},'home:house':{transforms:{[key(leo)]:transform(9999,9999)}}});
const changes=studioPeopleChanges(raw,['highschool:house','highschool'],[leo,mia]);
assert.equal(changes.length,2);
assert.deepEqual(changes[0].placement,{...leo,at:[415,1211],turn:35,y:80,scale:1.2});
assert.ok(!changes[1].placement.desk&&!changes[1].placement.station,'a manually moved desk user becomes a free placement');
const seed={cast:[leo,mia],when:{[leo.key]:[[1,9,.3,.4]]},chair:{back:700,side:50,turn:10},fade:.6};
const adopted=peopleEditsFromStudio(seed,[changes[0]]);
assert.deepEqual(adopted.cast[1],mia,'unselected people stay as authored');
assert.deepEqual(adopted.when,seed.when);
assert.deepEqual(adopted.chair,seed.chair);
assert.equal(adopted.fade,.6);
assert.deepEqual(seed.cast[0],leo,'the original cast remains available to Undo');
const recast=studioPeopleChanges(raw,['highschool:house'],[{...leo,id:'people-ben-sit-read'}]);
assert.equal(recast[0].placement.id,'people-ben-sit-read','a placement transfer preserves a character recast in Director');
assert.equal(studioPeopleChanges(raw,['highschool:house'],adopted.cast).length,1,'already adopted placements are not offered again');
assert.equal(studioPeopleChanges(raw,['highschool:apartment'],[leo,mia]).length,0,'other room sizes do not leak in');
assert.deepEqual(studioPeopleChanges('bad json',['highschool:house'],[leo]),[]);
const rows=adoptRows({peopleChanges:changes,peopleEdits:adopted});
assert.equal(rows[0].kind,'person');assert.equal(rows[0].name,'Leo');assert.ok(rows[0].conflict);
const removed=JSON.stringify({'highschool:house':{removed:[key(leo)]}});
const deletion=studioPeopleChanges(removed,['highschool:house'],[leo]);
assert.equal(peopleEditsFromStudio(seed,deletion).cast[0].hide,true);
assert.equal(studioPeopleChanges(removed,['highschool:house'],[{...leo,hide:true}]).length,0);
console.log('PASS Studio people sync: coordinates, turn, size, desk-user placement, selective adoption, cast/timing preservation, deduplication, room isolation and removal.');

import assert from 'node:assert/strict';
import { solveFloorMove, overlapArea, translateBox } from '../room-collision.mjs';
const b=(x,z,w=1,d=1)=>({minX:x,maxX:x+w,minZ:z,maxZ:z+d,minY:0,maxY:1});
const floor={minX:-5,maxX:10,minZ:-5,maxZ:10},desk=b(0,0);
let result=solveFloorMove(desk,{x:5,z:0},[{id:'cabinet',box:b(2,0),movable:false}],floor);
assert.equal(result.blocked,true);assert.ok(result.x<=1.001);assert.deepEqual(result.pushes,[]);
result=solveFloorMove(desk,{x:2,z:0},[{id:'chair',box:b(2,0),movable:true}],floor);
assert.equal(result.blocked,false);assert.ok(result.pushes[0].x>1);
assert.equal(overlapArea(translateBox(desk,result.x,result.z),translateBox(b(2,0),result.pushes[0].x,result.pushes[0].z)),0);
result=solveFloorMove(desk,{x:5,z:0},[{id:'chair',box:b(2,0),movable:true},{id:'cabinet',box:b(4,0),movable:false}],floor);
assert.equal(result.blocked,true);assert.ok(result.x<=2.002);assert.ok(result.pushes[0].x<=1.001);
result=solveFloorMove(desk,{x:2,z:0},[{id:'chair1',box:b(1.5,0),movable:true},{id:'chair2',box:b(2.6,0),movable:true}],floor);
assert.equal(result.blocked,false);assert.equal(result.pushes.length,2);
result=solveFloorMove(desk,{x:3,z:0},[{id:'chair',box:b(2,0),movable:true}],{...floor,maxX:4});
assert.equal(result.blocked,true);assert.ok(result.x<2.01);
result=solveFloorMove(desk,{x:-1,z:0},[{id:'authored-overlap',box:b(.5,0),movable:false}],floor);
assert.equal(result.blocked,false,'Existing overlap can separate');
result=solveFloorMove(desk,{x:2,z:0},[{id:'raised',box:{...b(2,0),minY:2,maxY:3},movable:false}],floor);
assert.equal(result.blocked,false,'Raised objects do not block floor movement');
result=solveFloorMove(desk,{x:2,z:2},[{id:'chair',box:b(1.5,1.5),movable:true}],floor);
assert.equal(result.blocked,false);assert.ok(result.pushes[0].x>1&&result.pushes[0].z>1,'Diagonal contact pushes along travel');
console.log('Floor contacts: swept blocking, chair pushes, push chains, walls, existing overlap escape, height and diagonal movement pass.');

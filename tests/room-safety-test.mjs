import assert from 'node:assert/strict';
import { firstDeskContact, RoomSafety } from '../room-safety.mjs';
const box=(x,z=0)=>({minX:x,maxX:x+1,minZ:z,maxZ:z+1,minY:0,maxY:1});
const desk=box(0),chair={id:'chair',name:'Chair',pushable:true,box:box(2)},cabinet={id:'cabinet',name:'Cabinet',pushable:false,box:box(2)};
assert.equal(firstDeskContact(desk,{x:10,z:0},[cabinet]).fraction,.1,'Sweep catches fast movement');
assert.equal(firstDeskContact(desk,{x:0,z:10},[cabinet]),null,'Parallel path does not trigger');
assert.equal(firstDeskContact(desk,{x:-1,z:0},[{...cabinet,box:box(.5)}],.15),null,'Can retreat from overlap');
assert.equal(firstDeskContact(desk,{x:10,z:0},[{...cabinet,box:{...box(2),minY:2,maxY:3}}]),null,'Height filter');
const safety=new RoomSafety();let stop=safety.check(desk,{x:3,z:0},[chair],.001);
assert.equal(stop.event.kind,'contact');assert.ok(stop.x<1&&stop.x>.99);assert.equal(stop.blocked,true);
assert.deepEqual(safety.check(desk,{x:-1,z:0},[],.001),{x:0,z:0,blocked:true},'Latched until clear');
safety.clear();assert.equal(safety.check(box(stop.x),{x:3,z:0},[chair],.001),null,'Portable acknowledged object can be pushed');
safety.check(box(-3),{x:-.1,z:0},[chair],.001);assert.ok(safety.check(desk,{x:3,z:0},[chair],.001)?.event,'Later encounter alerts again');
safety.reset();safety.guard=true;stop=safety.check(desk,{x:3,z:0},[cabinet],.001);
assert.equal(stop.event.kind,'ahead');assert.ok(Math.abs(stop.x-.85)<.001,'15 cm stop clearance');
safety.clear();assert.ok(safety.check(box(.85),{x:.2,z:0},[cabinet],.001)?.event,'CLEAR cannot bypass a guarded object');
safety.clear();assert.equal(safety.check(box(.85),{x:-.2,z:0},[cabinet],.001),null,'Can retreat after CLEAR');
assert.ok(safety.turn(desk,box(1.1),[cabinet],.001)?.event,'Turning uses guard clearance');
console.log('Desk safety: swept contact, latch/CLEAR, portable acknowledgement, repeat encounters, guard clearance, retreat, height and turning pass.');

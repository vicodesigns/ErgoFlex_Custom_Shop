import assert from 'node:assert/strict';
import {cleanBuildPresets} from '../build-presets.mjs';
import {SHARED_BUILD_PRESETS} from '../preset-defaults.mjs';
const occ=structuredClone(SHARED_BUILD_PRESETS.occ);
occ.room.desks.main.objects['accessory-logitech-mx-master'].transform.p.x=440;
occ.room.desks.main.objects['owner-decoration']={role:'desktop',added:true,propId:'apple',label:'My apple',transform:{p:{x:200,y:0,z:60},q:{x:0,y:0,z:0,w:1},s:{x:1000,y:1000,z:1000}}};
occ.initialView={position:{x:1,y:2,z:3},target:{x:0,y:0,z:0},fov:35};
const original=structuredClone(occ);
let data=cleanBuildPresets({v:1,active:'occ',entries:{occ}});
const wide=data.entries.occ,narrow=wide.sizeSetups['48x30'];
assert.deepEqual(occ,original,'migration leaves the owner source untouched');
assert.equal(narrow.config.size,'48x30');assert.equal(narrow.room.desks.main.size,'48x30');
assert.equal(narrow.room.desks.main.objects['accessory-logitech-mx-master'].transform.p.x,352);
assert.equal(narrow.room.desks.main.objects['owner-decoration'].transform.p.x,160);
assert.deepEqual(narrow.config.accessories,wide.config.accessories);
assert.deepEqual(narrow.initialView,wide.initialView);
assert.deepEqual(narrow.room.desks.main.objects['accessory-logitech-mx-master'].transform.s,wide.room.desks.main.objects['accessory-logitech-mx-master'].transform.s,'inputs keep physical scale');
narrow.config.woodFinish='White Birch';narrow.room.desks.main.objects['owner-decoration'].transform.p.x=-55;
narrow.initialView.position.x=5;
data=cleanBuildPresets(data);
assert.equal(data.entries.occ.config.woodFinish,'Coast Navy');
assert.equal(data.entries.occ.room.desks.main.objects['owner-decoration'].transform.p.x,200);
assert.equal(data.entries.occ.sizeSetups['48x30'].room.desks.main.objects['owner-decoration'].transform.p.x,-55,'edited narrow placement is not seeded again');
assert.equal(data.entries.occ.initialView.position.x,1,'each size owns its camera');
assert.deepEqual(cleanBuildPresets(data),data,'size migration is idempotent');
const office=cleanBuildPresets(null).entries.office.sizeSetups['48x30'].room.desks.main.objects;
assert.ok(office['accessory-wide-monitor'].transform.p.x-office['accessory-portrait-monitor'].transform.p.x>590,'seeded panel pair keeps a gap');
const lost=structuredClone(SHARED_BUILD_PRESETS.occ);lost.config.accessories=lost.config.accessories.filter(id=>id!=='wide-monitor');delete lost.room.desks.main.objects['accessory-wide-monitor'];
const recovered=cleanBuildPresets({entries:{occ:lost}}).entries.occ;assert.ok(recovered.config.accessories.includes('wide-monitor'),'legacy OCC resize loss is recovered');
recovered.config.accessories=recovered.config.accessories.filter(id=>id!=='wide-monitor');delete recovered.room.desks.main.objects['accessory-wide-monitor'];
assert.ok(!cleanBuildPresets({entries:{occ:recovered}}).entries.occ.config.accessories.includes('wide-monitor'),'new authored removal stays removed');
const architect=cleanBuildPresets(null).entries.architect;
for(const draft of [architect,architect.sizeSetups['48x30']])assert.ok(draft.config.accessories.includes('easel-rail'),'Architect support rail is present in both widths');
architect.config.accessories=architect.config.accessories.filter(id=>id!=='easel-rail');assert.ok(!cleanBuildPresets({entries:{architect}}).entries.architect.config.accessories.includes('easel-rail'),'later authored rail removal is retained');
console.log('Preset size migration preserves owner data, physical scale, independent edits, camera and panel clearance.');

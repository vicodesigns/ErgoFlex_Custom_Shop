import assert from 'node:assert/strict';
import { validArtwork, cleanArtwork, defaultArtworkLayer, artworkSummary, artworkLayers, ARTWORK_MAX_TOTAL_CHARS } from '../artwork-config.mjs';
import { defaultConfig, validConfig, cleanConfig, priceBreakdown } from '../catalog.mjs';
const image = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aIWQAAAAASUVORK5CYII=';
const artwork = { version: 1, surfaces: { desktop: { logo: { ...defaultArtworkLayer('logo'), name: 'Logo.png', image, x: 74, rotation: 30 } },
    'left-panel': { texture: { ...defaultArtworkLayer('texture'), name: 'Pattern.png', image } } } };
assert.ok(validArtwork(artwork));
const config = { ...defaultConfig(), artwork };
assert.ok(validConfig(config));
assert.deepEqual(cleanConfig(JSON.parse(JSON.stringify(config))).artwork, artwork);
const normalized = cleanArtwork({ ...artwork, surfaces: { desktop: { logo: { ...artwork.surfaces.desktop.logo, x: 999, scale: -3 } } } });
assert.equal(normalized.surfaces.desktop.logo.x, 200); assert.equal(normalized.surfaces.desktop.logo.scale, 5);
assert.equal(priceBreakdown(config).filter(l => l.label.startsWith('Premium artwork')).length, 2);
assert.ok(priceBreakdown(config).filter(l => l.label.startsWith('Premium artwork')).every(l => l.quoted && l.price === 0));
assert.match(artworkSummary(artwork)[0], /removable decal/);
assert.equal(validArtwork({ ...artwork, surfaces: { desktop: { logo: { ...artwork.surfaces.desktop.logo, image: 'https://example.com/logo.png' } } } }), false);
assert.equal(validArtwork({ ...artwork, surfaces: { desktop: { logo: { ...artwork.surfaces.desktop.logo, image: 'data:image/svg+xml;base64,PHN2Zz4=' } } } }), false);
assert.equal(validArtwork({ ...artwork, surfaces: { unknown: artwork.surfaces.desktop } }), false);
assert.equal(validArtwork({ ...artwork, surfaces: { desktop: { logo: { ...artwork.surfaces.desktop.logo, scale: NaN } } } }), false);
const overBudget = { version: 1, surfaces: {} }, fatImage = 'data:image/png;base64,' + 'A'.repeat(650000);
for (const id of ['desktop','left-panel','right-panel']) overBudget.surfaces[id] = { logo: { name: '', image: fatImage }, texture: { name: '', image: fatImage } };
assert.ok(fatImage.length * 6 > ARTWORK_MAX_TOTAL_CHARS); assert.equal(validArtwork(overBudget), false);
assert.equal(validConfig({ ...defaultConfig(), artwork: overBudget }), false);
assert.deepEqual(cleanArtwork(null), { version: 1, surfaces: {} });
assert.equal(cleanConfig(defaultConfig()).artwork, undefined);
const multiple = structuredClone(artwork);
multiple.surfaces.desktop['logo-2'] = { ...defaultArtworkLayer('logo'), name: 'Seal.png', image, x: 23, scale: 20 };
multiple.surfaces.desktop['texture-2'] = { ...defaultArtworkLayer('texture'), name: 'Wrap.png', image };
assert.ok(validConfig({ ...defaultConfig(), artwork: multiple }));
assert.deepEqual(cleanArtwork(multiple).surfaces.desktop['logo-2'], multiple.surfaces.desktop['logo-2']);
assert.deepEqual(artworkLayers(multiple.surfaces.desktop).map(([key]) => key), ['texture-2', 'logo', 'logo-2']);
assert.match(artworkSummary(multiple)[0], /Texture.*Graphic.*Graphic/);
assert.equal(validArtwork({ version: 1, surfaces: { desktop: { 'logo-9': multiple.surfaces.desktop.logo } } }), false);
console.log('Artwork validation, portable recipes, quote pricing, resource limits and legacy builds passed.');

import assert from 'node:assert/strict';
import {splitGraphic,editGraphic,graphicTrack} from '../experience/graphic-clips.mjs';
import {screenTiming} from '../tools/experience/screen-timing.mjs';
import {cleanShot} from '../experience/cuts.mjs';
import {filmRenderShot} from '../experience/film-render.mjs';
const original=[{src:'screen.mp4',offset:3,rate:2,start:2,end:18},{src:'other.mp4'}];
const parts=splitGraphic(original,0,8,20);
assert.equal(parts.length,3);assert.equal(parts[0].end,8);assert.equal(parts[1].start,8);assert.equal(parts[1].offset,15);
assert.equal(parts[0].target,0);assert.equal(parts[1].target,0);assert.equal(parts[2].target,1);
assert.equal(graphicTrack(parts[0]),graphicTrack(parts[1]));
assert.deepEqual(screenTiming(parts[1],9),screenTiming(original[0],9));
assert.equal(screenTiming(parts[0],8).visible,false);assert.equal(screenTiming(parts[1],8).visible,true);
const moved=editGraphic(parts,1,10,20,20);
assert.equal(moved[1].offset,15);assert.deepEqual(moved[0],parts[0]);
const extended=editGraphic(moved,0,2,9,20);assert.equal(extended[0].end,9);
const trimmed=editGraphic(moved,1,11,20,20,{trimStart:true});assert.equal(trimmed[1].offset,17);
assert.equal(screenTiming(trimmed[1],12).seconds,screenTiming(moved[1],12).seconds);
const recovered=editGraphic(trimmed,1,10,20,20,{trimStart:true});assert.equal(recovered[1].offset,15);
assert.throws(()=>editGraphic(parts,0,2,9,20),/overlaps/);
assert.throws(()=>splitGraphic(parts,0,2,20),/playhead/);assert.throws(()=>splitGraphic(parts,0,8,20),/playhead/);
assert.deepEqual(original,[{src:'screen.mp4',offset:3,rate:2,start:2,end:18},{src:'other.mp4'}],'edits never mutate the undo source');
const saved=cleanShot({id:'awaken',seconds:20,screens:moved});
assert.deepEqual(saved.screens,moved);assert.deepEqual(filmRenderShot({},saved,[]).screens,moved);
console.log('Graphics clips: split continuity, fixed screen targets, independent moves, source-aware trim/extend, collision protection and export: PASS');

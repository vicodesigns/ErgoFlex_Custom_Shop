#!/usr/bin/env python3
"""Chapter 7 (wellness) of Vico's 3rd cuts: Desk Squats (the app's desk_squats_01) instead of the arm stretch, Nov 20 2026.

  build-wellness-squats.py <cut dir>
Maya's break person (maya-break) stands as people-maya-stand-type (not stand-wait: that is the desk user's own standing key, a step out to it would have no length) and does three squats: placement act
{kind: 'squat', at, dur, reps} (room-people-motion.mjs squatAct). The chapter grows 16 -> 19.5 s: everything from the end
of the old stretch window (12.3 s) moves 3.5 s later. The screens (scenes/c07l, c07t) follow in opts.squats.
Writes the chapter in review-cut.json, director-film/wellness.json, director-camera-wellness.json (format kept). Data edits only."""
import copy, json, os, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
def load(p): return json.load(open(p, encoding='utf-8'))
def dump(p, d): open(p, 'w', encoding='utf-8', newline='\n').write(json.dumps(d, indent=1, ensure_ascii=True))
def r4(x): return round(float(x), 4)
def bake(seconds, plan):
    with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as t:
        json.dump({'seconds': seconds, 'cameraPlan': plan}, t); tmp = t.name
    try:
        subprocess.run(['node', os.path.join(HERE, 'camera-spline.mjs'), tmp], check=True, stdout=subprocess.DEVNULL); return load(tmp)['camera']
    finally: os.unlink(tmp)
cut = sys.argv[1].rstrip('/' + chr(92)); rel = 'exports/' + os.path.basename(os.path.abspath(cut))
SHIFT, AFTER = 3.5, 12.3
ACT = {'kind': 'squat', 'at': 10.2, 'dur': 5.2, 'reps': 3}
WINDOW = [9.7, 15.8, 0.3, 0.35]
rc = os.path.join(cut, 'review-cut.json'); cd = load(rc); shot = next(s for s in cd['shots'] if s['id'] == 'wellness')
if shot['seconds'] != 16: sys.exit('wellness is not the 16 s chapter: already built?')
shot['seconds'] = 16 + SHIFT
keys = [{**k, 'at': r4(k['at'] + SHIFT)} if k['at'] > AFTER else k for k in shot['cameraPlan']['keys']]
old = next(k for k in shot['cameraPlan']['keys'] if abs(k['at'] - 11) < 1e-6)
keys.append({**copy.deepcopy(old), 'at': 14.5, 'label': 'Desk Squats: the view holds on her'}); keys.sort(key=lambda k: k['at'])
shot['cameraPlan']['keys'] = keys; shot['camera'] = bake(shot['seconds'], shot['cameraPlan'])
p = shot['people']; br = next(c for c in p['cast'] if c['key'] == 'maya-break')
br['id'] = 'people-maya-stand-type'; br['turn'] = 0; br['act'] = dict(ACT); p['when']['maya-break'] = [list(WINDOW)]
mode = 'a' if cut.endswith('-standing') else 'b'
for s in shot['screens']: s['src'] = f'{rel}/screens/cine3{mode}-wellness-' + ('main' if s['target'] == 'main-landscape' else 'tablet') + '.mp4'   # regenerated by tools/experience/screens (scenes/cine-wellness.js, opts.squats)
cd['shots'] = [shot if s['id'] == 'wellness' else s for s in cd['shots']]; dump(rc, cd)
dump(os.path.join(cut, 'director-film', 'wellness.json'), shot)
dc = os.path.join(cut, 'director-camera-wellness.json'); d = load(dc)
d['seconds'] = shot['seconds']; d['keys'] = shot['cameraPlan']['keys']; d['people'] = {'v': 2, **p} if 'v' in d.get('people', {}) else p
dump(dc, d); print('wellness: 16 ->', shot['seconds'], 's')
